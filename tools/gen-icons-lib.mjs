// Usage: node tools/gen-icons-lib.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const dir = path.join(root, 'node_modules', 'lucide-static', 'icons');
const NAMES = [
  'panel-left', 'panel-right', 'layout-grid', 'bell', 'plus', 'chevron-right', 'chevron-down',
  'chevron-left', 'chevron-up', 'moon', 'sun', 'settings', 'wrench', 'check', 'square-terminal',
  'audio-lines', 'arrow-up', 'x', 'layout-template', 'globe', 'ellipsis', 'maximize-2', 'minimize-2',
  'folder', 'folder-open', 'folder-plus', 'git-branch', 'file-diff', 'paperclip', 'shield', 'shield-check',
  'shield-alert', 'brain', 'square', 'rotate-cw', 'arrow-left', 'arrow-right', 'monitor', 'smartphone',
  'external-link', 'trash-2', 'pin', 'pin-off', 'pencil', 'clock', 'play', 'search', 'command', 'sparkles',
  'message-square', 'bot', 'circle-check', 'circle-alert', 'copy', 'terminal', 'file-text', 'list-todo',
  'lightbulb', 'lock', 'refresh-cw', 'columns-2', 'rows-2', 'grid-2x2', 'wand-sparkles', 'history',
  'calendar-clock', 'zap', 'eye', 'file-pen', 'file-search', 'list', 'hand', 'circle-stop', 'info',
  'keyboard', 'user', 'mic', 'send', 'loader', 'circle', 'square-pen', 'panel-bottom', 'app-window', 'waypoints',
  'users', 'messages-square', 'minus', 'plug', 'plug-zap', 'circle-play', 'skip-forward', 'key-round', 'route', 'undo-2',
];

const out = {};
const missing = [];
for (const name of NAMES) {
  const file = path.join(dir, name + '.svg');
  if (!fs.existsSync(file)) { missing.push(name); continue; }
  const svg = fs.readFileSync(file, 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '').trim();
  out[name] = inner;
}
const body = '// Generated by tools/gen-icons-lib.mjs — Lucide icons (ISC). Do not edit by hand.\n'
  + 'export const ICONS = ' + JSON.stringify(out, null, 0).replace(/","/g, '",\n"') + ';\n';
fs.writeFileSync(path.join(root, 'renderer', 'js', 'icons.js'), body);
console.log('icons:', Object.keys(out).length, 'missing:', missing.join(', ') || 'none');
